#!/usr/bin/env python3
from __future__ import annotations
"""
ingest_openhands.py -- Download and convert OpenHands SWE-bench Lite evaluation
outputs into clean agentic simulation traces (RequestTrace / IterSpec).

Each trace captures:
  - session_id (e.g. SWE-bench task instance)
  - turns:
      - tokens_added: new prompt tokens for this turn (prefill)
      - gen_tokens: tokens generated by the LLM (decode)
      - tool_time: exact wall-clock seconds waiting for the tool to execute
      - ctx_tokens: accumulated context length
"""

import json
import os
import sys
import urllib.request
from datetime import datetime

DATASET_URL = (
    "https://huggingface.co/datasets/OpenHands/openhands-evaluation-outputs/resolve/main/"
    "outputs/SWE-bench_Lite-test/CodeActAgent/claude-3-5-sonnet-20241022_maxiter_100_N_v2.1-no-hint/output.jsonl"
)


def parse_instance(line: str) -> dict | None:
    data = json.loads(line)
    instance_id = data.get("instance_id")
    history = data.get("history", [])
    if not history:
        return None

    iters = []
    prev_ctx = 0

    # Pair actions with subsequent observations
    i = 0
    while i < len(history):
        event = history[i]
        action = event.get("action")

        # Check if this event represents an LLM tool call or generation
        meta = event.get("tool_call_metadata") or {}
        mr = meta.get("model_response") or {}
        usage = mr.get("usage")

        if usage and action in ("run", "run_ipython", "message", "finish"):
            prompt_tokens = usage.get("prompt_tokens", 0)
            completion_tokens = usage.get("completion_tokens", 0)

            # Look for the immediate observation to calculate tool duration
            tool_time = 0.0
            if i + 1 < len(history):
                next_ev = history[i + 1]
                if next_ev.get("observation") is not None:
                    try:
                        t_act = datetime.fromisoformat(event.get("timestamp"))
                        t_obs = datetime.fromisoformat(next_ev.get("timestamp"))
                        tool_time = max(0.01, (t_obs - t_act).total_seconds())
                    except Exception:
                        tool_time = 1.0

            tokens_added = max(1, prompt_tokens - prev_ctx) if prev_ctx > 0 else prompt_tokens
            prev_ctx = prompt_tokens + completion_tokens

            iters.append({
                "tokens_added": tokens_added,
                "gen_tokens": max(1, completion_tokens),
                "tool_time": tool_time,
                "ctx_tokens": prompt_tokens + completion_tokens
            })
        i += 1

    if not iters:
        return None

    return {
        "session_id": instance_id,
        "num_turns": len(iters),
        "total_tokens": prev_ctx,
        "iters": iters
    }


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "data/swebench_traces.jsonl"
    max_instances = int(sys.argv[2]) if len(sys.argv) > 2 else 50

    print(f"[Ingest] Fetching OpenHands SWE-bench Lite dataset from Hugging Face...")
    req = urllib.request.Request(DATASET_URL, headers={"User-Agent": "Mozilla/5.0"})

    records = []
    with urllib.request.urlopen(req) as resp:
        for idx, line in enumerate(resp):
            if idx >= max_instances:
                break
            line_str = line.decode("utf-8").strip()
            if not line_str:
                continue
            parsed = parse_instance(line_str)
            if parsed and parsed["iters"]:
                records.append(parsed)
                print(f"  Parsed {parsed['session_id']}: {parsed['num_turns']} turns, final context {parsed['total_tokens']} tokens")

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")

    print(f"[Ingest] Successfully saved {len(records)} traces to {out_path}")


if __name__ == "__main__":
    main()
